"""Availability checks: a failure is confirmed by a retry, and firewall/bot-protection pages are reported as
"blocked our checker" (degraded), not as the site being down."""

from __future__ import annotations

import socket

import httpx
import pytest

from app.core.http import set_transport_factory
from app.monitoring.availability import check_availability, detect_firewall


@pytest.fixture
def public_dns(monkeypatch):
    monkeypatch.setattr(socket, "getaddrinfo", lambda h, p, *a, **k: [
        (socket.AF_INET, socket.SOCK_STREAM, 6, "", ("93.184.216.34", p))])
    yield
    set_transport_factory(None)


def _serve(*responses):
    it = iter(responses)
    seen = []

    def handler(request):
        seen.append(request)
        r = next(it)
        if isinstance(r, Exception):
            raise r
        return r

    set_transport_factory(lambda: httpx.MockTransport(handler))
    return seen


def test_single_failure_recovered_on_retry_is_not_an_outage(public_dns):
    seen = _serve(httpx.ConnectError("reset"), httpx.Response(200, text="ok"))
    res = check_availability("https://example.com/", retry_after=0)
    assert res.outcome == "up" and "recovered on retry" in res.error_message
    assert len(seen) == 2
    assert seen[0].headers["accept"].startswith("text/html") and "CyberWatch" in seen[0].headers["user-agent"]


def test_failure_confirmed_by_retry_stays_down(public_dns):
    _serve(httpx.Response(502, text="Bad gateway"), httpx.Response(502, text="Bad gateway"))
    res = check_availability("https://example.com/", retry_after=0)
    assert res.outcome == "down" and "confirmed by a second attempt" in res.error_message


def test_no_retry_when_up_or_degraded(public_dns):
    seen = _serve(httpx.Response(404, text="nope"))
    assert check_availability("https://example.com/", retry_after=0).outcome == "degraded"
    assert len(seen) == 1


@pytest.mark.parametrize("status,headers,body,name", [
    (403, {}, b"<html><title>Imunify360 bot-protection</title>", "Imunify360"),
    (503, {}, b"<title>Just a moment...</title>", "Cloudflare"),
    (403, {"cf-mitigated": "challenge"}, b"", "Cloudflare"),
    (406, {}, b"<h1>Not Acceptable!</h1> ... Mod_Security", "ModSecurity"),
    (403, {"x-sucuri-id": "1"}, b"Access Denied - Sucuri Website Firewall", "Sucuri"),
    (503, {}, b"Your access to this site has been limited. Generated by Wordfence", "Wordfence"),
])
def test_firewall_pages_are_blocked_not_down(public_dns, status, headers, body, name):
    assert detect_firewall(status, httpx.Headers(headers), body) == name
    _serve(httpx.Response(status, headers=headers, content=body))
    res = check_availability("https://example.com/", retry_after=0)
    assert res.outcome == "degraded" and res.error_class == "blocked_by_firewall" and name in res.error_message


def test_real_server_errors_are_not_mistaken_for_firewalls():
    assert detect_firewall(503, httpx.Headers({}), b"<h1>Service Unavailable</h1>") is None
    assert detect_firewall(200, httpx.Headers({}), b"imunify360 mentioned in a blog post") is None


def test_availability_report_command(alice, capsys, monkeypatch):
    from datetime import timedelta

    from app import cli
    from app.db.base import utcnow
    from app.db.session import platform_session
    from app.models import AvailabilityCheck
    from app.monitoring.availability import AvailabilityResult
    from tests.test_security import _make_site

    sess, tid = alice
    wid = _make_site(sess, tid, url="https://saber.example.org/")
    with platform_session() as db:
        for i in range(3):
            db.add(AvailabilityCheck(tenant_id=tid, website_id=wid, outcome="down", error_class="timeout",
                                     error_message="The website did not respond in time.",
                                     checked_at=utcnow() - timedelta(hours=i)))
        db.add(AvailabilityCheck(tenant_id=tid, website_id=wid, outcome="up", http_status=200, checked_at=utcnow()))
        db.commit()
    monkeypatch.setattr("app.monitoring.availability.check_availability",
                        lambda url, retry_after=None: AvailabilityResult("up", http_status=200, response_ms=321))
    cli.main(["availability-report", "saber.example.org"])
    out = capsys.readouterr().out
    assert "4 checks" in out and "timeout" in out and "Failures by hour" in out and "Live check now: up HTTP 200 321 ms" in out
